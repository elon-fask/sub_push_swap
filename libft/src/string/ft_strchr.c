#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	unsigned char	uc;

	uc = (unsigned char)c;
	while (*s && (unsigned char)*s != uc)
		s++;
	if ((unsigned char)*s == uc)
		return ((char *)s);
	return (NULL);
}
